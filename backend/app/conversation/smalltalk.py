_PUNCT = re.compile(
    r"[\s，。！？!?,.:：;；、\"'“”‘’（）()\[\]【】《》·…\-_/\\]"
)


def _normalize(message: str) -> str:
    return _PUNCT.sub("", message).strip().lower()


def classify_smalltalk(message: str) -> tuple[str, str] | None:
    """判断一条消息是否为闲聊/身份/问候/致谢。

    返回 (类别, 回复话术)；不是闲聊时返回 None。
    """
    text = _normalize(message)
    if not text or len(text) > 24:
        return None
    if any(hint in text for hint in _CREATION_HINTS):
        return None
    for category, patterns in _PATTERNS:
        for pattern in patterns:
            if text == pattern:
                return category, _REPLIES[category]
            # 「你好呀」「谢谢啦」：模式 + 纯语气词后缀
            if (
                len(pattern) >= 2
                and text.startswith(pattern)
                and text[len(pattern):]
                and set(text[len(pattern):]) <= _PARTICLES
            ):
                return category, _REPLIES[category]
    return None
